from ml_service.rag.chunker import chunk_document, get_doc_hash

def test_chunker_merges_short_and_overlaps():
    """Тест 1: короткие склеиваются, длинные режутся с перекрытием (ML-09.5)."""
    text = (
        "Заголовок приказа\n\n"
        "Первое короткое предложение. Второе предложение для склейки. "
        "Третье предложение, которое должно сделать текст достаточно длинным для начала проверки лимитов. "
        "Четвертое предложение. Пятое длинное предложение, которое уже должно спровоцировать "
        "перенос текста в следующий чанк, так как мы превышаем лимит символов, установленный в 400-800. "
        "Шестое предложение. Седьмое предложение."
    )
    
    # Для теста временно уменьшим лимиты прямо в тексте (эмулируем длинный текст)
    # В реальной жизни 800 символов - это большой абзац.
    # Проверим, что заголовок подхватился
    chunks = chunk_document(text, doc_id="doc_1")
    
    assert len(chunks) > 0
    assert chunks[0]["doc_id"] == "doc_1"
    assert chunks[0]["section_title"] == "Заголовок приказа"
    
    # Проверка идемпотентности (одинаковый хеш для всех чанков одного документа)
    doc_hash = get_doc_hash(text)
    assert all(c["doc_hash"] == doc_hash for c in chunks)

def test_idempotency_hash():
    """Тест 4: Повторная загрузка даст тот же хеш, исключая дубликаты (ML-09.5)."""
    text = "Какой-то важный текст документа."
    hash1 = get_doc_hash(text)
    hash2 = get_doc_hash(text)
    assert hash1 == hash2
    